#!/usr/bin/env node
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildDocsCatalog } from "./docs-catalog-builder.mjs";

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const pluginRoot = join(repoRoot, "plugins/dioxus-ui");
const referencesDir = join(pluginRoot, "skills/dioxus-ui/references");

export function readWorkspaceVersion(root = repoRoot) {
  const cargoToml = readFileSync(join(root, "Cargo.toml"), "utf8");
  const match = cargoToml.match(/^\[workspace\.package\][^[]*?^version = "([^"]+)"/m);
  if (!match) {
    throw new Error("Cargo.toml is missing [workspace.package] version");
  }
  return match[1];
}

export function loadBlocks(root = repoRoot) {
  const blocksDir = join(root, "crates/dioxus-shadcn-cli/blocks");
  return readdirSync(blocksDir)
    .filter((file) => file.endsWith(".json"))
    .sort()
    .map((file) => {
      const entry = JSON.parse(readFileSync(join(blocksDir, file), "utf8"));
      const sourceFile = entry.files?.[0]?.source;
      const sourceText = sourceFile
        ? readFileSync(join(root, "crates/dioxus-shadcn-cli", sourceFile), "utf8")
        : "";
      const componentMatch = sourceText.match(/#\[component\]\s*pub fn ([A-Za-z0-9_]+)/);
      return {
        name: entry.name,
        description: entry.description,
        target: entry.files?.[0]?.target ?? `src/blocks/${entry.name}.rs`,
        component: componentMatch?.[1] ?? `${entry.name}Block`,
        dependencies: [...(entry.dependencies ?? [])].sort(),
      };
    });
}

export function loadThemes(root = repoRoot) {
  const themesDir = join(root, "crates/dioxus-shadcn-cli/themes");
  return readdirSync(themesDir)
    .filter((file) => file.endsWith(".css"))
    .sort()
    .map((file) => {
      const name = file.slice(0, -".css".length);
      const css = readFileSync(join(themesDir, file), "utf8");
      const scheme = css.match(/color-scheme:\s*(light|dark)/)?.[1] ?? "unknown";
      return { name, scheme };
    });
}

export function renderCatalogReference(root = repoRoot) {
  const version = readWorkspaceVersion(root);
  const { catalog, catalogCategories } = buildDocsCatalog({ repoRoot: root });
  const lines = [
    "# Dioxus UI Component Catalog",
    "",
    `<!-- Generated by scripts/claude-plugin-sync.mjs for dioxus-shadcn ${version}. Do not edit by hand. -->`,
    "",
    `Synced with \`dioxus-shadcn\` **${version}** (${catalog.length} public components across ${catalogCategories.length} categories).`,
    "",
    `- **Crate mode**: add the feature under \`dioxus-shadcn = { version = "${version.split(".").slice(0, 2).join(".")}", default-features = false, features = [...] }\` and import from \`dioxus_shadcn::<module>\` (or crate root re-exports).`,
    "- **Source-copy mode**: run `dxui add <slug>` and import from `crate::components::ui::<module>`.",
    "- **Live docs & examples**: `https://ui.dioxuspress.dev/components/<slug>`",
    "",
  ];

  for (const category of catalogCategories) {
    const items = catalog.filter((item) => item.category === category.id);
    if (items.length === 0) {
      continue;
    }
    lines.push(`## ${category.label} (${items.length})`, "");
    lines.push("| Component | Feature / `dxui add` | Module | Description |");
    lines.push("| :--- | :--- | :--- | :--- |");
    for (const item of items) {
      const desc = (item.description ?? "").replaceAll("|", "\\|").trim();
      lines.push(`| ${item.title} | \`${item.name}\` | \`${item.crate_import}\` | ${desc} |`);
    }
    lines.push("");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

export function renderBlocksReference(root = repoRoot) {
  const version = readWorkspaceVersion(root);
  const blocks = loadBlocks(root);
  const lines = [
    "# Dioxus UI Blocks Catalog",
    "",
    `<!-- Generated by scripts/claude-plugin-sync.mjs for dioxus-shadcn ${version}. Do not edit by hand. -->`,
    "",
    `Synced with \`dioxus-shadcn-cli\` **${version}** (${blocks.length} ready-made full-screen blocks).`,
    "",
    "Blocks are source-copy starter screens (`dxui add <block>`) written to `src/blocks/<name>.rs` and declared in `src/blocks/mod.rs`. Each command also adds the component dependencies it needs under `src/components/ui/`.",
    "",
    "```rust",
    "mod blocks;",
    "mod components;",
    "",
    "fn App() -> Element {",
    "  rsx! { blocks::login::LoginBlock {} }",
    "}",
    "```",
    "",
    "| Block | Command | Component | Target | Dependencies | Screen |",
    "| :--- | :--- | :--- | :--- | :--- | :--- |",
  ];

  for (const block of blocks) {
    const deps = block.dependencies.map((dep) => `\`${dep}\``).join(", ");
    const desc = (block.description ?? "").replaceAll("|", "\\|").trim();
    lines.push(
      `| ${block.name} | \`dxui add ${block.name}\` | \`${block.component}\` | \`${block.target}\` | ${deps} | ${desc} |`,
    );
  }

  lines.push("");
  return `${lines.join("\n").trimEnd()}\n`;
}

export function renderThemesReference(root = repoRoot) {
  const version = readWorkspaceVersion(root);
  const themes = loadThemes(root);
  const lightThemes = themes.filter((theme) => theme.scheme === "light").map((theme) => theme.name);
  const darkThemes = themes.filter((theme) => theme.scheme === "dark").map((theme) => theme.name);

  const lines = [
    "# Dioxus UI Themes & Semantic Tokens",
    "",
    `<!-- Generated by scripts/claude-plugin-sync.mjs for dioxus-shadcn ${version}. Do not edit by hand. -->`,
    "",
    `Synced with \`dioxus-shadcn-cli\` **${version}** (${themes.length} WCAG-AA presets: ${lightThemes.length} light, ${darkThemes.length} dark).`,
    "",
    "## Stylesheet Setup (`dxui init`)",
    "",
    "`dxui init` writes a Tailwind CSS v4 input stylesheet to `assets/dioxus-shadcn.css` containing `@import \"tailwindcss\";`, `@custom-variant dark (&:is(.dark *));`, `:root` light tokens, `.dark` overrides, and `@theme inline` mappings. In Crate Mode it also inserts the `@source` directive pointing to the installed `dioxus-shadcn` crate source (rerun `dxui init` after upgrading the crate).",
    "",
    "## Core Semantic Tokens",
    "",
    "- **Surfaces & text**: `--background`, `--foreground`, `--card`, `--card-foreground`, `--popover`, `--popover-foreground`",
    "- **Actions & accents**: `--primary`, `--primary-foreground`, `--secondary`, `--secondary-foreground`, `--muted`, `--muted-foreground`, `--accent`, `--accent-foreground`",
    "- **Status**: `--destructive`, `--destructive-foreground`, `--success`, `--success-foreground`, `--warning`, `--warning-foreground`, `--info`, `--info-foreground`",
    "- **Chrome & geometry**: `--border`, `--input`, `--ring`, `--radius` (`--radius-sm`/`md`/`lg`/`xl`)",
    "- **Charts & sidebar**: `--chart-1`..`--chart-5`, `--sidebar`, `--sidebar-foreground`, `--sidebar-primary`, `--sidebar-primary-foreground`, `--sidebar-accent`, `--sidebar-accent-foreground`, `--sidebar-border`, `--sidebar-ring`",
    "",
    "Rebrand by redefining token variables in `:root` and `.dark` (for example `--primary`, `--primary-foreground`, `--ring`, and `--radius`).",
    "",
    "## Built-in Dark Mode",
    "",
    "```rust",
    "div { class: \"dark min-h-screen bg-background text-foreground\", App {} }",
    "```",
    "",
    "## Theme Presets (`dxui theme`)",
    "",
    "```bash",
    "dxui theme list",
    "dxui theme add nord dracula",
    "```",
    "",
    "Apply a preset via `data-theme` (dark presets set `color-scheme: dark` automatically without the `dark` class):",
    "",
    "```rust",
    "div { \"data-theme\": \"nord\", class: \"min-h-screen bg-background text-foreground\", App {} }",
    "```",
    "",
    `### Light Presets (${lightThemes.length})`,
    "",
    lightThemes.map((name) => `\`${name}\``).join(" · "),
    "",
    `### Dark Presets (${darkThemes.length})`,
    "",
    darkThemes.map((name) => `\`${name}\``).join(" · "),
    "",
  ];

  return `${lines.join("\n").trimEnd()}\n`;
}

export function renderGeneratedPluginFiles(root = repoRoot) {
  return {
    "plugins/dioxus-ui/skills/dioxus-ui/references/catalog.md": renderCatalogReference(root),
    "plugins/dioxus-ui/skills/dioxus-ui/references/blocks.md": renderBlocksReference(root),
    "plugins/dioxus-ui/skills/dioxus-ui/references/themes.md": renderThemesReference(root),
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const checkOnly = process.argv.includes("--check");
  const files = renderGeneratedPluginFiles(repoRoot);

  if (checkOnly) {
    const stale = [];
    for (const [relativePath, expected] of Object.entries(files)) {
      const actual = readFileSync(join(repoRoot, relativePath), "utf8");
      if (actual !== expected) {
        stale.push(relativePath);
      }
    }
    if (stale.length > 0) {
      console.error("Claude Code plugin generated references are out of date:");
      for (const path of stale) {
        console.error(`- ${path}`);
      }
      console.error("Run `npm run claude-plugin:sync` to regenerate them.");
      process.exitCode = 1;
    } else {
      console.log(`Claude Code plugin references are up to date (${Object.keys(files).length} files)`);
    }
  } else {
    mkdirSync(referencesDir, { recursive: true });
    for (const [relativePath, content] of Object.entries(files)) {
      writeFileSync(join(repoRoot, relativePath), content, "utf8");
    }
    console.log(
      `synced ${Object.keys(files).length} Claude Code plugin reference files for version ${readWorkspaceVersion(repoRoot)}`,
    );
  }
}
